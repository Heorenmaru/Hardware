void D_Init(st7567Handler* h)
{


//	RST=1;
	HAL_Delay(10);
//	RST=0;
	HAL_Delay(10);
//	RST=1;
	HAL_Delay(10);



	Dcmd(h, 0xe2);//soft reset

	HAL_Delay(10);


	Dcmd(h, 0x2c);  	//Control built-in power circuit ON	    VB
	Dcmd(h, 0x2e);  	//Control built-in power circuit ON	    VR
	Dcmd(h, 0x2f);  	//Control built-in power circuit ON	    VF

	HAL_Delay(10);


	Dcmd(h, 0xf8);  //Set booster level
	Dcmd(h, 0x00);  //Set  4X booster level

	Dcmd(h, 0x25);  //Select regulation resistor ratio
	Dcmd(h, 0x81);  	 //Setelectronic volume (EV) level
	Dcmd(h, dispContrast);  //Setelectronic volume (EV) level
	Dcmd(h, 0xa2);  //1/9bias
	Dcmd(h, 0xc8);  //Set output direction of COM
	Dcmd(h, 0xa0);  //Set scan direction of SEG
	Dcmd(h, 0xa4);  //Set normal display

	Dcmd(h, 0xa6);  //Set normal display

	Dcmd(h, 0x40);  //start line
	Dcmd(h, 0xaf);  //  display ON


}


void Set_Contrast_Control_Register(st7567Handler* h, uint8_t mod)
{
	Dcmd(h, 0x81);
	Dcmd(h, mod);
}


// Set page address 0~8
void Set_Page_Address(st7567Handler* h, uint8_t add)
{
    add=0xb0|add;
    Dcmd(h, add);
}

void Set_Column_Address(st7567Handler* h, uint8_t add)
{
	Dcmd(h, (0x10|(add>>4)));
	Dcmd(h, (0x0f&add));
}



void Set_Pos(st7567Handler* h, uint8_t x, uint8_t y)
{

	Dcmd(h, 0xb0+y);
	Dcmd(h, ((x&0xf0)>>4)|0x10);
	Dcmd(h, (x&0x0f));

}



