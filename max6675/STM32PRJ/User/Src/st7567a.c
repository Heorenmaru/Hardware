void ShowString(st7567Handler* h, uint8_t x,uint8_t y,uint8_t *chr)
{
	uint8_t j=0;
	while (chr[j]!='\0')
	{		ShowChar(h, x,y,chr[j]);
			x+=8;
		if(x>124)
		{
			x=0;
			y+=1;
		}
			j++;
	}
}



void Dcls(st7567Handler* h)
{
	uint8_t i,j;

	for(i=0;i<8;i++)
	{
		Set_Page_Address(h, i);
		Set_Column_Address(h, 0x00);
        for(j=0;j<132;j++)
		{
		    Ddat(h, 0x00);
		}

	}

}
