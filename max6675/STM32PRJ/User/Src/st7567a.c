#include "st7567a.h"


void Dcmd(st7567Handler* h, uint8_t c){
	h->nss.port->ODR &= ~h->nss.pin;
	h->dc.port->ODR &= ~h->dc.pin;
	HAL_SPI_Transmit(h->spi,&c,1,150);
	h->nss.port->ODR |= h->nss.pin;
	h->dc.port->ODR |= h->dc.pin;
}

void Ddat(st7567Handler* h, uint8_t c){
	h->nss.port->ODR &= ~h->nss.pin;
	h->dc.port->ODR |= h->dc.pin;
	HAL_SPI_Transmit(h->spi,&c,1,150);
	h->nss.port->ODR |= h->nss.pin;
	h->dc.port->ODR |= h->dc.pin;
}


void D_WriteByte(st7567Handler* h, uint8_t TxData){
    HAL_SPI_Transmit(h->spi,&TxData,1,150);
}


